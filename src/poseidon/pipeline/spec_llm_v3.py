"""Step 6: spec_generate v3 (idea text -> spec v3 + clauses) for idea-only runs (design 2026-10-24 §3.8).

One LLM attempt decides the route. The system prompt is rendered from the component registry
(``v3.brief.catalog``, the machine form of the capability brief) and allows four replies:

- ``ok``: a spec v3 document, the clauses that map every sentence of the idea to a slot/component,
  and the assumptions (defaults the idea did not state);
- ``unsupported``: the idea needs something the registry cannot express;
- ``ambiguous``: the idea does not say which daily series a signal reads (owner decision 2026-10-24
  afternoon #1: never picked silently), or another choice only the owner can make;
- ``intraday``: an intraday idea. Until DSL parity (step 7) it is generated by the DSL v2 path of
  :mod:`poseidon.pipeline.spec_llm`, unchanged, with the intraday config's own settings.

Program checks on an ``ok`` reply, all fed back to the model (at most ``max_repair_rounds`` repairs):
the v3 validator (``validate_spec_v3``); every clause quote is a verbatim substring of the idea; every
sentence of the idea is cited by at least one clause; a cited component is one the spec uses; every
``signal`` series is one the idea names (a keyword net under the prompt rule); and the optional
``review(idea_text, clauses, spec)`` hook (the JEV reviewer, ``faithfulness.FaithfulnessReviewer``),
called once a spec passes every program check. Its items get at most one repair round, fed back like
validator errors. JEV is report-only until the owner's control set qualifies it (§4): the spec the
reviewer saw stays the fallback, so a reply to its feedback that fails a check, or a disagreement left
after the repair, never fails the attempt (``review_unresolved`` / ``review_repair`` in the report).

Key discipline, identity check and the cost cap are those of :mod:`poseidon.pipeline.spec_llm`
(same key ``STRATEGY_PIPELINE_OPENROUTER_KEY``, same pin, no other variable is read). The idea text is
untrusted data and the prompt says so.
"""

